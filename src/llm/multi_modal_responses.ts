/**
 * Multi-Modal Response Generation for LLM Statistical Inquiry
 *
 * Given a statistical analysis result, produces:
 * - Reproducible code in R, Python, and JavaScript
 * - Visualization recommendations with chart specifications
 * - Plain-language statistical interpretation
 *
 * The code generators emit deterministic, runnable scripts so that an analyst
 * can reproduce the analysis without hand-writing it.
 */

import { RAnalysisResult } from '../r-interface/r_bridge';

export enum CodeLanguage {
  R = 'r',
  PYTHON = 'python',
  JAVASCRIPT = 'javascript'
}

export enum ChartType {
  BAR = 'bar',
  GROUPED_BAR = 'grouped_bar',
  SCATTER = 'scatter',
  FOREST_PLOT = 'forest_plot',
  TIME_SERIES = 'time_series',
  HEATMAP = 'heatmap',
  DISTRIBUTION = 'distribution',
  EFFECT_SIZE = 'effect_size'
}

export interface CodeArtifact {
  language: CodeLanguage;
  filename: string;
  code: string;
  description: string;
  requiresPackages: string[];
}

export interface VisualizationRecommendation {
  chartType: ChartType;
  title: string;
  rationale: string;
  xAxis: string;
  yAxis: string;
  /** Whether the chart should show confidence intervals */
  showConfidenceIntervals: boolean;
  accessibilityNotes: string[];
}

export interface StatisticalInterpretation {
  headline: string;
  effectDescription: string;
  significanceDescription: string;
  confidenceDescription: string;
  uncertaintyLevel: 'low' | 'moderate' | 'high';
  caveats: string[];
  recommendedFollowUps: string[];
}

export interface MultiModalResponse {
  code: CodeArtifact[];
  visualizations: VisualizationRecommendation[];
  interpretation: StatisticalInterpretation;
  /** Overall confidence in the response, 0-1 */
  responseConfidence: number;
}

