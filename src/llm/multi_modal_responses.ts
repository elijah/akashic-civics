/**
 * Generate runnable R code reproducing the analysis
 */
export function generateRCode(
  result: RAnalysisResult,
  outcomeVariable: string = 'outcome',
  groupVariable: string = 'group'
): CodeArtifact {
  const code = `# Reproduce: ${result.analysis_type}
# Generated by Akashic Civics multi-modal response generator

library(stats)

# Load your data
# df <- read.csv("data.csv")

fit <- glm(
  ${outcomeVariable} ~ ${groupVariable},
  data = df,
  family = binomial()
)

summary(fit)

# Effect size: odds ratio
or <- exp(coef(fit)[2])
cat(sprintf("Odds ratio: %.4f\\n", or))

# 95% confidence interval
ci_or <- exp(confint(fit)[2, ])
cat(sprintf("95%% CI: [%.4f, %.4f]\\n", ci_or[1], ci_or[2]))

# Two-sided test
p_value <- summary(fit)$coefficients[2, 4]
cat(sprintf("p-value: %.6f\\n", p_value))

# --- Disconfirmation checks ---
# 1. Placebo test: rerun on a permuted outcome
set.seed(42)
perm_fit <- glm(
  ${outcomeVariable} ~ ${groupVariable},
  data = transform(df, ${outcomeVariable} = sample(df$${outcomeVariable})),
  family = binomial()
)
cat(sprintf("Placebo p-value: %.6f\\n", summary(perm_fit)$coefficients[2, 4]))

# 2. Specification sensitivity
fit_alt <- glm(
  ${outcomeVariable} ~ ${groupVariable} + offense_severity,
  data = df,
  family = binomial()
)
cat(sprintf("Alternative spec OR: %.4f\\n", exp(coef(fit_alt)[2])))
`;

  return {
    language: CodeLanguage.R,
    filename: 'analysis.R',
    code,
    description: `R script reproducing the ${result.analysis_type} analysis with disconfirmation checks`,
    requiresPackages: ['stats']
  };
}

/**
 * Generate runnable Python code reproducing the analysis
 */
export function generatePythonCode(
  result: RAnalysisResult,
  outcomeVariable: string = 'outcome',
  groupVariable: string = 'group'
): CodeArtifact {
  const code = `"""Reproduce: ${result.analysis_type}
Generated by Akashic Civics multi-modal response generator
"""

import statsmodels.formula.api as smf
import numpy as np

# Load your data
# df = pd.read_csv("data.csv")

model = smf.logit(
    f"${outcomeVariable} ~ ${groupVariable}",
    data=df
).fit(disp=False)

print(model.summary())

# Effect size: odds ratio
odds_ratios = np.exp(model.params)
print("Odds ratio:", odds_ratios.iloc[1])

# 95% confidence interval
ci = model.conf_int()
print("95% CI:", np.exp(ci.iloc[1]))

# Two-sided test
print("p-value:", model.pvalues.iloc[1])

# --- Disconfirmation checks ---
# 1. Placebo test: rerun on a permuted outcome
np.random.seed(42)
df_placebo = df.copy()
df_placebo["${outcomeVariable}"] = np.random.permutation(df["${outcomeVariable}"])
placebo_model = smf.logit(
    f"${outcomeVariable} ~ ${groupVariable}",
    data=df_placebo
).fit(disp=False)
print("Placebo p-value:", placebo_model.pvalues.iloc[1])

# 2. Specification sensitivity
alt_model = smf.logit(
    f"${outcomeVariable} ~ ${groupVariable} + offense_severity",
    data=df
).fit(disp=False)
print("Alternative spec OR:", np.exp(alt_model.params).iloc[1])
`;

  return {
    language: CodeLanguage.PYTHON,
    filename: 'analysis.py',
    code,
    description: `Python script reproducing the ${result.analysis_type} analysis with disconfirmation checks`,
    requiresPackages: ['statsmodels', 'numpy', 'pandas']
  };
}

/**
 * Generate runnable JavaScript code reproducing the analysis
 */
export function generateJavaScriptCode(
  result: RAnalysisResult,
  outcomeVariable: string = 'outcome',
  groupVariable: string = 'group'
): CodeArtifact {
  const code = `/**
 * Reproduce: ${result.analysis_type}
 * Generated by Akashic Civics multi-modal response generator
 */

import { runLogisticRegression } from './logistic_regression';

const data = cases.map(c => ({
  ${outcomeVariable}: c.${outcomeVariable},
  ${groupVariable}: c.${groupVariable},
  offense_severity: c.offense_severity
}));

const result = runLogisticRegression(data, ['${groupVariable}'], '${outcomeVariable}');

console.log('Coefficients:', result.coefficients);
console.log('P-value:', result.coefficients['${groupVariable}'].p_value);
console.log('Odds ratio:', result.odds_ratio);

// --- Disconfirmation checks ---
// 1. Placebo test: permute the outcome and re-run
const permuted = data.map(d => ({ ...d }));
for (let i = permuted.length - 1; i > 0; i--) {
  const j = Math.floor(Math.random() * (i + 1));
  [permuted[i]['${outcomeVariable}'], permuted[j]['${outcomeVariable}']] =
    [permuted[j]['${outcomeVariable}'], permuted[i]['${outcomeVariable}']];
}
const placebo = runLogisticRegression(permuted, ['${groupVariable}'], '${outcomeVariable}');
console.log('Placebo p-value:', placebo.coefficients['${groupVariable}'].p_value);
`;

  return {
    language: CodeLanguage.JAVASCRIPT,
    filename: 'analysis.js',
    code,
    description: `JavaScript script reproducing the ${result.analysis_type} analysis using the Akashic Civics statistical layer`,
    requiresPackages: []
  };
}

/**
 * Generate code artifacts in all supported languages
 */
export function generateAllCode(
  result: RAnalysisResult,
  outcomeVariable: string = 'outcome',
  groupVariable: string = 'group'
): CodeArtifact[] {
  return [
    generateRCode(result, outcomeVariable, groupVariable),
    generatePythonCode(result, outcomeVariable, groupVariable),
    generateJavaScriptCode(result, outcomeVariable, groupVariable)
  ];
}

