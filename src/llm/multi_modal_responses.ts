/**
 * Produce a plain-language statistical interpretation of the analysis
 */
export function interpretResult(
  result: RAnalysisResult,
  analysisName: string = 'the analysis'
): StatisticalInterpretation {
  const [lo, hi] = result.confidence_interval;
  const effectSize = result.effect_size;
  const pValue = result.p_value;
  const ciWidth = hi - lo;
  const ciRelativeWidth = effectSize !== 0 ? ciWidth / Math.abs(effectSize) : Infinity;

  const direction = effectSize > 0 ? 'higher' : effectSize < 0 ? 'lower' : 'equal';
  const significant = pValue < 0.05;
  const crossesNull = lo <= 0 && hi >= 0;

  const uncertaintyLevel: 'low' | 'moderate' | 'high' =
    !significant ? 'high' : ciRelativeWidth > 2 ? 'high' : ciRelativeWidth > 1 ? 'moderate' : 'low';

  const caveats: string[] = [];
  if (!significant) {
    caveats.push('The result is not statistically significant at the conventional 0.05 level.');
  }
  if (crossesNull) {
    caveats.push('The confidence interval includes the null value, so the direction of the effect is uncertain.');
  }
  if (ciRelativeWidth > 1) {
    caveats.push('The confidence interval is wide relative to the point estimate, indicating imprecise measurement.');
  }
  caveats.push('Statistical significance does not establish causation.');
  caveats.push('Unmeasured confounders may account for some or all of the observed effect.');

  const recommendedFollowUps = [
    'Run a specification sensitivity check across reasonable analytical variations',
    'Test the finding against a placebo outcome where no effect is hypothesized',
    'Evaluate measured alternative explanations for the disparity',
    'Replicate on an independent time period or jurisdiction'
  ];

  return {
    headline: significant
      ? `${analysisName} shows a statistically significant difference (p = ${pValue.toFixed(4)}).`
      : `${analysisName} does not show a statistically significant difference (p = ${pValue.toFixed(4)}).`,
    effectDescription: `The estimated effect size is ${effectSize.toFixed(4)}, indicating a ${direction} outcome for the focal group relative to the reference group.`,
    significanceDescription: significant
      ? `The result is statistically significant at alpha = 0.05 (p = ${pValue.toFixed(4)}).`
      : `The result does not reach statistical significance at alpha = 0.05 (p = ${pValue.toFixed(4)}).`,
    confidenceDescription: `The 95% confidence interval is [${lo.toFixed(4)}, ${hi.toFixed(4)}], a width of ${ciWidth.toFixed(4)}.`,
    uncertaintyLevel,
    caveats,
    recommendedFollowUps
  };
}

