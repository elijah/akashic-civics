/**
 * Confidence in the overall response, driven by the evidential quality of the
 * underlying analysis rather than by the fluency of the output.
 */
export function scoreResponseConfidence(
  result: RAnalysisResult,
  interpretation: StatisticalInterpretation
): number {
  let confidence = 0.5;

  // Significance contributes
  if (result.p_value < 0.05) confidence += 0.2;
  if (result.p_value < 0.01) confidence += 0.05;

  // Tight, null-excluding intervals contribute
  const [lo, hi] = result.confidence_interval;
  const crossesNull = lo <= 0 && hi >= 0;
  if (!crossesNull) confidence += 0.15;
  const ciWidth = hi - lo;
  if (result.effect_size !== 0 && ciWidth / Math.abs(result.effect_size) < 1) {
    confidence += 0.1;
  }

  // High uncertainty caps the score
  if (interpretation.uncertaintyLevel === 'high') {
    confidence = Math.min(confidence, 0.5);
  }

  return Math.max(0, Math.min(1, confidence));
}

/**
 * Build a complete multi-modal response for an analysis result
 */
export function generateMultiModalResponse(
  result: RAnalysisResult,
  options?: {
    analysisName?: string;
    outcomeVariable?: string;
    groupVariable?: string;
    hasGroupingVariable?: boolean;
    hasTimeVariable?: boolean;
  }
): MultiModalResponse {
  const analysisName = options?.analysisName ?? 'This analysis';
  const interpretation = interpretResult(result, analysisName);
  const code = generateAllCode(
    result,
    options?.outcomeVariable,
    options?.groupVariable
  );
  const visualizations = recommendVisualizations(
    result,
    options?.hasGroupingVariable ?? true,
    options?.hasTimeVariable ?? false
  );

  return {
    code,
    visualizations,
    interpretation,
    responseConfidence: scoreResponseConfidence(result, interpretation)
  };
}
