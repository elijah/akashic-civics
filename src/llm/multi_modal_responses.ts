/**
 * Recommend visualizations appropriate to the analysis type and findings
 */
export function recommendVisualizations(
  result: RAnalysisResult,
  hasGroupingVariable: boolean = true,
  hasTimeVariable: boolean = false
): VisualizationRecommendation[] {
  const recommendations: VisualizationRecommendation[] = [];
  const analysisLabel = result.analysis_type.replace(/_/g, ' ');

  if (hasTimeVariable) {
    recommendations.push({
      chartType: ChartType.TIME_SERIES,
      title: 'Metric Over Time',
      rationale: `A time series reveals whether the ${analysisLabel} result is persistent or a period-specific artifact.`,
      xAxis: 'Time period',
      yAxis: 'Conviction rate',
      showConfidenceIntervals: true,
      accessibilityNotes: [
        'Do not rely on color alone to mark the threshold line; use a dashed line',
        'Label the y-axis with units'
      ]
    });
  }

  if (hasGroupingVariable) {
    recommendations.push({
      chartType: ChartType.GROUPED_BAR,
      title: 'Outcome by Group',
      rationale: 'Grouped bars make the magnitude of the disparity directly comparable.',
      xAxis: 'Group',
      yAxis: 'Conviction rate',
      showConfidenceIntervals: true,
      accessibilityNotes: [
        'Use a colorblind-safe palette (e.g. Okabe-Ito)',
        'Include the confidence interval in the caption, not only visually'
      ]
    });
  }

  recommendations.push({
    chartType: ChartType.FOREST_PLOT,
    title: 'Effect Size with Confidence Interval',
    rationale: 'A forest plot shows the effect size against the null line and displays uncertainty directly.',
    xAxis: 'Effect size (odds ratio)',
    yAxis: 'Specification / subgroup',
    showConfidenceIntervals: true,
    accessibilityNotes: [
      'Mark the null value (OR = 1) with a distinct vertical reference line',
      'Print the numeric estimate and CI as text alongside the marker'
    ]
  });

  recommendations.push({
    chartType: ChartType.DISTRIBUTION,
    title: 'Outcome Distribution by Group',
    rationale: 'Overlaid distributions reveal whether the aggregate difference is driven by a subgroup.',
    xAxis: 'Outcome value',
    yAxis: 'Density',
    showConfidenceIntervals: false,
    accessibilityNotes: [
      'Provide a table equivalent for screen reader users',
      'Distinguish groups with line style as well as color'
    ]
  });

  return recommendations;
}

